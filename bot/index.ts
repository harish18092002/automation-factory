// ── Slack message handler ─────────────────────────────────────────────────────
// Using `any` on the handler args is intentional pre-install: @slack/bolt types
// are not resolved until `npm install` runs. After install, the destructured
// params (message, say, client) are fully typed by @slack/bolt's own generics.
// eslint-disable-next-line @typescript-eslint/no-explicit-any
app.message(async ({ message, say, client: slackClient }: any) => {
  // Ignore bot messages, edits, and message_changed/message_deleted subtypes
  if (message.subtype) return;
  if (!message.text) return;
  // Only respond to top-level messages, not thread replies
  if (message.thread_ts && message.thread_ts !== message.ts) return;

  const threadTs: string = message.ts;
  const channelId: string = message.channel;

  // 1. Acknowledge immediately
  await say({ text: '🔍 Parsing your request...', thread_ts: threadTs });

  // 2. Parse intent
  let intent: ParsedIntent | null;
  try {
    intent = await parseIntent(message.text as string);
  } catch (err) {
    await say({ text: `❌ Intent parsing failed: ${String(err)}`, thread_ts: threadTs });
    return;
  }

  if (!intent) {
    await say({
      text: [
        '❌ Could not determine the target repo from your message.',
        '',
        `*Available repos:* \`${repoAliases.join('`, `')}\``,
        '',
        '*Example requests:*',
        '• _"In the services repo, add a health endpoint to merchant-service"_',
        '• _"Fix the null-check bug in terminal repo datecs-acquiring service"_',
        '• _"Refactor swells payment-isolate to extract validateOrder into utils"_',
      ].join('\n'),
      thread_ts: threadTs,
    });
    return;
  }

  // 3. Confirm understanding
  await say({
    text: [
      '✅ *Task understood*',
      `• Repo: \`${intent.repo}\``,
      `• Service: \`${intent.service ?? 'N/A (repo-wide)'}\``,
      `• Type: \`${intent.taskType}\``,
      '',
      `📋 *Task:* ${intent.fullTask}`,
      '',
      '⚙️ Starting agent...',
    ].join('\n'),
    thread_ts: threadTs,
  });

  // 4. Run agent loop — streams live tool-call updates into the Slack thread
  const progressCallback = async (update: string): Promise<void> => {
    await slackClient.chat.postMessage({
      channel: channelId,
      thread_ts: threadTs,
      text: update,
      mrkdwn: true,
    });
  };

  let agentResult: string;
  try {
    agentResult = await runAgentLoop(
      intent.repo,
      intent.fullTask,
      intent.service ?? undefined,
      progressCallback
    );
  } catch (err) {
    await say({ text: `❌ *Agent error*: ${String(err)}`, thread_ts: threadTs });
    return;
  }

  // 5. Final summary
  // NOTE: Git commit/push (Phase 2) will go here once enabled.
  // Replace the block below with commitAndPushBranch() when Phase 2 lands.
  await say({
    text: [
      '✅ *Task Complete*',
      '',
      agentResult,
      '',
      '---',
      '📝 *Next step (manual for now)*: review the changes in the repo, then commit & push.',
    ].join('\n'),
    thread_ts: threadTs,
    mrkdwn: true,
  });
});

// ── Start ─────────────────────────────────────────────────────────────────────
(async () => {
  await app.start();
  console.log('⚡ Claude Agent Bot is running (Socket Mode)');
  console.log(`📦 Registered repos: ${repoAliases.join(', ')}`);
  console.log(`🤖 Model: ${MODEL}`);
  console.log('📡 Git host: git.surfboard.se (GitLab — Phase 2 will auto-push branches)');
})();
