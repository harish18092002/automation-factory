import { App } from '@slack/bolt';
import Anthropic from '@anthropic-ai/sdk';
import 'dotenv/config';
import { runAgentLoop } from '../agent/loop';
import repoConfig from '../agent/repos.config.json';

// ── Validation ────────────────────────────────────────────────────────────────
const REQUIRED_ENV = ['SLACK_BOT_TOKEN', 'SLACK_APP_TOKEN', 'ANTHROPIC_API_KEY'];
for (const key of REQUIRED_ENV) {
  if (!process.env[key]) {
    console.error(`Missing required environment variable: ${key}`);
    process.exit(1);
  }
}

// ── Slack App (Socket Mode — no public URL required) ──────────────────────────
const app = new App({
  token: process.env.SLACK_BOT_TOKEN!,
  appToken: process.env.SLACK_APP_TOKEN!,
  socketMode: true,
});

// ── Claude client (reads ANTHROPIC_API_KEY from env automatically) ────────────
const claude = new Anthropic();

const MODEL = 'claude-sonnet-4-20250514';
const repoAliases = Object.keys(repoConfig.repos) as Array<keyof typeof repoConfig.repos>;

// ── Intent types ──────────────────────────────────────────────────────────────
interface ParsedIntent {
  repo: string;
  service: string | null;
  taskType: 'feature' | 'bugfix' | 'refactor' | 'test' | 'other';
  /** Short kebab-case label — reserved for future branch naming (max 50 chars) */
  description: string;
  /** Full task instruction forwarded to the agent loop */
  fullTask: string;
}

// ── Intent parser — separate Claude call with tight JSON schema ───────────────
async function parseIntent(userMessage: string): Promise<ParsedIntent | null> {
  const serviceMap = Object.fromEntries(
    repoAliases.map((alias) => [alias, repoConfig.repos[alias].services ?? []])
  );

  const res = await claude.messages.create({
    model: MODEL,
    max_tokens: 600,
    system: [
      'You are a strict intent-parsing assistant for a multi-repo engineering bot.',
      '',
      `Available repos: ${repoAliases.join(', ')}`,
      `Services per repo: ${JSON.stringify(serviceMap, null, 2)}`,
      '',
      'Extract a JSON object from the user message.',
      'Respond with ONLY valid JSON — no markdown, no backticks, no explanation.',
      'Schema:',
      '{',
      '  "repo": string,          // must match one of the available repos exactly, or null if unclear',
      '  "service": string|null,  // must match a service in that repo exactly, or null',
      '  "taskType": "feature"|"bugfix"|"refactor"|"test"|"other",',
      '  "description": string,   // max 50 chars, kebab-case, suitable for a git branch name',
      '  "fullTask": string       // the full task instruction for the AI agent',
      '}',
      '',
      'If you cannot determine the repo, set repo to null.',
      'If you cannot determine the service, set service to null.',
    ].join('\n'),
    messages: [{ role: 'user', content: userMessage }],
  });

  try {
    // Typed without relying on the package being installed — safe pre and post npm install
    const content = res.content as Array<{ type: string; text?: string }>;
    const textBlock = content.find((block) => block.type === 'text');
    if (!textBlock?.text) return null;

    const intent = JSON.parse(textBlock.text!) as ParsedIntent;
    if (!intent.repo || !(repoAliases as string[]).includes(intent.repo)) return null;
    return intent;
  } catch {
    return null;
  }
}

